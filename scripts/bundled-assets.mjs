// Generate once from qualified inputs; ordinary builds verify and copy committed assets.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { cpSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const root = resolve(import.meta.dirname, '..');
const source = join(root, 'src/runtime/assets');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
if (process.argv[2] === '--generate') {
  assert.equal(process.argv.length, 5, 'usage: --generate RUNTIME_PACKAGE PROVING_DIRECTORY');
  const runtime = resolve(process.argv[3]), proving = resolve(process.argv[4]);
  const manifestBytes = readFileSync(join(runtime, 'manifest.json'));
  const manifest = JSON.parse(manifestBytes);
  assert.equal(manifest.mode, 'baseline');
  const files = {};
  for (const file of manifest.files) {
    assert.match(file.url, /^[a-zA-Z0-9_.-]+$/);
    const bytes = readFileSync(join(runtime, file.url));
    assert.equal(bytes.length, file.byteLength);
    assert.equal(sha(bytes), file.sha256);
    files[`wallet/${file.url}`] = bytes;
  }
  files['wallet/manifest.json'] = manifestBytes;
  for (const name of ['build.json', 'dependency-graph.json', 'native-build.json', 'worker-inputs.json']) files[`wallet/${name}`] = readFileSync(join(runtime, name));
  assert.equal(sha(files['wallet/build.json']), manifest.buildSha256);
  assert.equal(sha(files['wallet/dependency-graph.json']), manifest.dependencyGraphSha256);
  assert.equal(sha(files['wallet/worker-inputs.json']), JSON.parse(files['wallet/build.json']).workerInputsSha256);
  const { saplingAssets } = await import('../dist/src/wallet/proving-assets.js');
  for (const asset of saplingAssets) {
    const bytes = readFileSync(join(proving, asset.assetId));
    assert.equal(bytes.length, asset.byteLength);
    assert.equal(sha(bytes), asset.sha256);
    files[`proving/${asset.assetId}`] = bytes;
  }
  files['wallet/LICENSE'] = readFileSync(join(runtime, 'LICENSE'));
  for (const entry of readdirSync(join(runtime, 'licenses'), { recursive: true, withFileTypes: true })) {
    if (entry.isFile()) {
      const name = join(entry.parentPath, entry.name).slice(join(runtime, 'licenses').length + 1);
      files[`wallet/licenses/${name}`] = readFileSync(join(runtime, 'licenses', name));
    }
  }
  mkdirSync(source); // Never overwrite a previously pinned inventory.
  for (const [name, bytes] of Object.entries(files)) {
    mkdirSync(join(source, name, '..'), { recursive: true });
    writeFileSync(join(source, name), bytes, { flag: 'wx' });
  }
  const inventory = Object.fromEntries(Object.entries(files).map(([name, bytes]) => [name, { sha256: sha(bytes), byteLength: bytes.length }]));
  writeFileSync(join(source, 'inventory.json'), JSON.stringify(inventory, null, 2) + '\n');
  const urls = [...manifest.files.map(file => `wallet/${file.url}`), 'wallet/manifest.json',
    ...saplingAssets.map(asset => `proving/${asset.assetId}`)];
  writeFileSync(join(root, 'src/runtime/bundled-assets.mjs'),
    '// Generated by scripts/bundled-assets.mjs; static URLs let browser bundlers emit lazy assets.\n' +
    'let urls;\nexport function bundledUrls() { return urls ??= Object.freeze({\n' + urls.map(name => `  ${JSON.stringify(name)}: new URL(${JSON.stringify(`./assets/${name}`)}, import.meta.url),`).join('\n') +
    '\n}); }\nexport const bundledArtifact = Object.freeze({ get manifestUrl() { return bundledUrls()["wallet/manifest.json"].href; }, manifestSha256: ' + JSON.stringify(sha(manifestBytes)) + ' });\n');
} else {
  assert.equal(process.argv.length, 2);
  const inventory = JSON.parse(readFileSync(join(source, 'inventory.json')));
  for (const [name, expected] of Object.entries(inventory)) {
    const bytes = readFileSync(join(source, name));
    assert.equal(bytes.length, expected.byteLength, name);
    assert.equal(sha(bytes), expected.sha256, name);
  }
  const { bundledArtifact } = await import(pathToFileURL(join(root, 'src/runtime/bundled-assets.mjs')));
  assert.equal(sha(readFileSync(join(source, 'wallet/manifest.json'))), bundledArtifact.manifestSha256,
    'stale bundled manifest pin');
  const workerInputs = JSON.parse(readFileSync(join(source, 'wallet/worker-inputs.json')));
  assert.ok(Object.keys(workerInputs).length, 'worker source inventory required');
  for (const [name, expected] of Object.entries(workerInputs)) {
    assert.ok(name.startsWith('dist/src/') && !name.includes('..'), 'worker source path');
    assert.equal(sha(readFileSync(join(root, name))), expected,
      `stale packaged worker: ${name}; regenerate the worker and runtime package`);
  }
  cpSync(source, join(root, 'dist/src/runtime/assets'), { recursive: true });
  for (const name of ['bundled-assets.mjs', 'bundled-assets.d.mts']) cpSync(join(root, 'src/runtime', name), join(root, 'dist/src/runtime', name));
}
